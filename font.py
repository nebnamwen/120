def render_text(layer, text, start, scale=(10.0, 20.0), color=(1.0, 1.0, 1.0), key="text", kerning=2.0):
    """Renders single-line text to the given 2D canvas layer.

    scale is a tuple (width, height) in pixels controlling character dimensions
    and aspect ratio. Returns the right side (x) of the last character drawn.
    """
    cursor_x, cursor_y = start
    char_w, char_h = scale

    for char in text.upper():
        strokes = HERSHEY_FONT.get(char, HERSHEY_FONT.get('?'))
        seg_start = None
        
        for pt in strokes:
            if pt is None:
                seg_start = None
            else:
                px = cursor_x + pt[0] * char_w
                py = cursor_y + pt[1] * char_h
                pt_coords = np.array([px, py], dtype=np.float32)
                
                if seg_start is not None:
                    layer.line(key, seg_start, pt_coords, color)
                seg_start = pt_coords
                
        cursor_x += char_w + kerning

    return cursor_x
